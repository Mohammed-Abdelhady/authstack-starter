function matrixRows(text: string): string[] {
  const code = encodeQrCode(text);
  if (code === null) throw new Error('QR fixture did not fit');
  return code.modules.map((row) => row.map((module) => (module ? '1' : '0')).join(''));
}

describe('QR encoder independent vectors', () => {
  it('matches the full Nayuki version 1-M matrix for one byte', () => {
    expect(matrixRows('A')).toEqual(VERSION_1M_BYTE_A);
  });

  it('matches a full Nayuki version 7-M matrix with alignment patterns', () => {
    expect(matrixRows(VERSION_7M_BYTE_PAYLOAD)).toEqual(VERSION_7M_BYTE_MATRIX);
  });

  it('matches the published QR Reed-Solomon remainder vector', () => {
    const data = Uint8Array.from([0x03, 0x3a, 0x60, 0x12, 0xc7]);

    expect([...remainder(data, 5)]).toEqual([0xcb, 0x36, 0x16, 0xfa, 0x9d]);
  });
});
