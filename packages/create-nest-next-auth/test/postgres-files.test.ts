/** What a MongoDB project deletes: what no project carries, and what PostgreSQL owns. */
async function removedFromMongoProject(): Promise<string[]> {
  const manifest = await loadManifest(REPOSITORY);
  return [...manifest.core.alwaysRemoveFiles, ...manifest.databases.postgres.files];
}

